def _clean_products(products_raw):
    df = products_raw.copy()
    df.columns = [str(c).strip() for c in df.columns]

    explicit_map = {
        "category.name": "category",
        "category_name": "category",
        "pricing.price": "price",
        "pricing.amount": "price",
        "price.amount": "price",
    }
    for col in list(df.columns):
        key = col.lower()
        if key in explicit_map:
            target = explicit_map[key]
            if target in df.columns:
                df[target] = df[target].fillna(df[col])
                df = df.drop(columns=[col])
            else:
                df = df.rename(columns={col: target})

    df.columns = [
        str(c).split(".")[-1].strip().lower() if "." in str(c) else str(c).strip().lower()
        for c in df.columns
    ]

    generic_map = {
        "id": "product_id",
        "productid": "product_id",
        "name": "product_name",
        "productname": "product_name",
        "title": "product_name",
        "cat": "category",
        "amount": "price",
        "unit_price": "price",
    }
    for src, target in generic_map.items():
        if src in df.columns and src != target:
            if target in df.columns:
                df[target] = df[target].fillna(df[src])
                df = df.drop(columns=[src])
            else:
                df = df.rename(columns={src: target})

    if "price" in df.columns:
        df["price"] = pd.to_numeric(
            df["price"].astype(str).str.replace(r"[^\d.\-]", "", regex=True),
            errors="coerce",
        )
    else:
        df["price"] = np.nan

    if "category" in df.columns:
        df["category"] = df["category"].astype(str).str.strip()
        df.loc[df["category"].isin(["", "nan", "None"]), "category"] = "Unknown"
        df["category"] = df["category"].fillna("Unknown")
    else:
        df["category"] = "Unknown"

    if "product_name" not in df.columns:
        df["product_name"] = "Unknown"
    df["product_name"] = df["product_name"].fillna("Unknown")

    before = len(df)
    df = df.drop_duplicates(subset="product_id", keep="first")
    logger.info("Products: dropped %d duplicate product_id rows", before - len(df))

